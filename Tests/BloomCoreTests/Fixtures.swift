    /// A 440 Hz tone as 16-bit WAV.
    static func audio(
        in folder: URL,
        name: String = "tone.wav",
        sampleRate: Double = 44_100,
        channels: AVAudioChannelCount = 2,
        seconds: Double = 1
    ) throws -> URL {
        let url = folder.appendingPathComponent(name)
        let settings: [String: Any] = [
            AVFormatIDKey: kAudioFormatLinearPCM,
            AVSampleRateKey: sampleRate,
            AVNumberOfChannelsKey: channels,
            AVLinearPCMBitDepthKey: 16,
            AVLinearPCMIsFloatKey: false,
            AVLinearPCMIsBigEndianKey: false,
            AVLinearPCMIsNonInterleaved: false,
        ]
        // AVAudioFile finishes the file only when it is deallocated, so drain it before anything reads the file.
        try autoreleasepool {
            let file = try AVAudioFile(forWriting: url, settings: settings)
            let frames = AVAudioFrameCount(sampleRate * seconds)
            guard let buffer = AVAudioPCMBuffer(pcmFormat: file.processingFormat, frameCapacity: frames),
                let samples = buffer.floatChannelData
            else { throw FixtureError("Couldn’t create the sample audio.") }
            buffer.frameLength = frames
            for frame in 0..<Int(frames) {
                let value = Float(sin(2 * Double.pi * 440 * Double(frame) / sampleRate) * 0.5)
                for channel in 0..<Int(channels) {
                    samples[channel][frame] = value
                }
            }
            try file.write(from: buffer)
        }
        return url
    }

    /// Two seconds of H.264 video with no soundtrack, like most screen recordings.
    static func silentVideo(in folder: URL, name: String = "recording.mov") async throws -> URL {
        let url = folder.appendingPathComponent(name)
        try await writeSilentVideo(to: url)
        return url
    }

    /// Two seconds of H.264 video with the sample tone as its soundtrack.
    static func video(in folder: URL) async throws -> URL {
        let silent = folder.appendingPathComponent("silent-\(UUID().uuidString).mov")
        let tone = try audio(in: folder, name: "soundtrack-\(UUID().uuidString).wav", seconds: 2)
        let url = folder.appendingPathComponent("clip.mov")
        try await writeSilentVideo(to: silent)
        try await combine(video: silent, audio: tone, into: url)
        try FileManager.default.removeItem(at: silent)
        try FileManager.default.removeItem(at: tone)
        return url
    }

    static func tarball(in folder: URL, containing file: URL) throws -> URL {
        let url = folder.appendingPathComponent("bundle.tar.gz")
        try run("/usr/bin/tar", ["-czf", url.path, "-C", file.deletingLastPathComponent().path, file.lastPathComponent])
        return url
    }

